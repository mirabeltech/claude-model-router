#!/usr/bin/env node
/**
 * Regenerates docs/environment.md: every environment variable this project reads.
 *
 * Two sources, because there are two kinds. The 76 `CMR_*` variables come from `SPEC`, so they
 * cannot drift from the settings they override. Everything else — a credential, a path the host
 * supplies, a kill switch, a test channel — comes from `lib/env-registry.mjs`, which is the only
 * place a non-setting variable may be declared.
 *
 * The whole file is generated. Unlike docs/configuration.md there is no hand-written half: this
 * document is an inventory, and an inventory with prose bolted on invites the prose to go stale
 * while the table stays right.
 *
 * CI runs this then `git diff --exit-code`, so an undeclared variable fails the build.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { SPEC, DEFAULTS, CONFIG_VERSION } from '../lib/config.mjs'
import { DESCRIPTIONS } from '../lib/config-descriptions.mjs'
import { DYNAMIC_READ_SITES, ENV_REGISTRY, SPEC_ENV_EXCEPTIONS } from '../lib/env-registry.mjs'

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const out = path.join(REPO_ROOT, 'docs', 'environment.md')

const esc = (s) => String(s).replace(/\|/g, '\\|')
const defaultOf = (field) =>
  field.split('.').reduce((o, k) => (o == null ? undefined : o[k]), DEFAULTS)

function renderDefault(value) {
  if (value === undefined) return '—'
  if (value === null) return '`null`'
  if (Array.isArray(value)) return value.length === 0 ? '`[]`' : `${value.length} entries`
  return `\`${JSON.stringify(value)}\``
}

const CLASS_ORDER = ['provider-secret', 'claude-code', 'side-channel', 'convention', 'os', 'test-only']
const CLASS_TITLES = {
  'provider-secret': 'Credentials',
  'claude-code': 'Supplied by Claude Code',
  'side-channel': 'Side channels',
  convention: 'Conventions we honour',
  os: 'Operating system and Node',
  'test-only': 'Internal and test-only',
}
const CLASS_BLURBS = {
  'provider-secret':
    'Never stored in configuration, never written to a telemetry row, and never printed. Doctor reports only presence, length and a four-character prefix, which is what makes its output safe to paste into an issue.',
  'claude-code':
    'Set by the host for a hook or a command. The code treats every one of these as optional and falls back, because a hook that threw on a missing variable would break the session it was meant to help.',
  'side-channel':
    'Deliberately without a `SPEC` entry. A switch that can only be reached by editing a file is not an emergency stop.',
  convention: 'Cross-tool conventions. We honour these rather than define them.',
  os: 'Supplied by the platform. Listed because the test harness sets them explicitly to isolate a child process from the developer’s real home directory.',
  'test-only': 'Read only by the test harness or the mock provider. None of these affects a real delegation.',
}

const lines = []
lines.push('# Environment variables')
lines.push('')
lines.push(
  'GENERATED by `npm run docs:env` from `SPEC` and `lib/env-registry.mjs`. Do not edit by hand.',
)
lines.push('')
lines.push(
  'Every variable this project reads is listed here. `test/env.inventory.test.mjs` scans the source',
  'and fails if a variable is read without being declared, or declared without being read — so this',
  'document cannot quietly fall behind the code.',
)
lines.push('')

/* --------------------------------------------------------------- settings */

const specFields = Object.keys(SPEC).filter((f) => SPEC[f].env)
lines.push('## Settings')
lines.push('')
lines.push(
  `${specFields.length} variables, one per setting, generated from \`SPEC\` (config version ${CONFIG_VERSION}).`,
  'Each overrides the matching setting from a config file, and is itself overridden only by a plugin',
  'option. This is how CI pins behaviour and how the kill switches work. What each setting MEANS is in',
  '[configuration.md](configuration.md); this table is the variable name, the type and the default.',
)
lines.push('')
lines.push('| Variable | Setting | Type | Default | Secret |')
lines.push('| --- | --- | --- | --- | --- |')
for (const field of specFields) {
  const spec = SPEC[field]
  lines.push(
    `| \`${spec.env}\` | \`${field}\` | ${spec.type} | ${renderDefault(defaultOf(field))} | no |`,
  )
}
lines.push('')
lines.push(
  'One setting has no variable: `version`, which describes the file it appears in rather than',
  'overriding behaviour.',
)
lines.push('')
lines.push(
  'A `string[]` variable is comma-separated. A boolean accepts `1/true/yes/on` and `0/false/no/off`.',
  'An invalid value falls back to the default and is reported by `npm run doctor` rather than throwing.',
)
lines.push('')
lines.push(
  '**No setting variable holds a secret.** `CMR_WORKER_API_KEY_ENV` sets the NAME of the variable that',
  'holds the key, never the key.',
)
lines.push('')

/* ------------------------------------------------------------- everything else */

lines.push('## Everything else')
lines.push('')
lines.push(
  'These are not settings, which is why they are declared in `lib/env-registry.mjs` rather than in',
  '`SPEC`: a secret whose variable name is itself configurable, a path the host supplies, a kill',
  'switch, a test channel. Putting them in `SPEC` would make the config loader claim to own values it',
  'does not.',
)
lines.push('')

for (const cls of CLASS_ORDER) {
  const entries = Object.entries(ENV_REGISTRY).filter(([, v]) => v.class === cls)
  if (entries.length === 0) continue
  lines.push(`### ${CLASS_TITLES[cls]}`)
  lines.push('')
  if (CLASS_BLURBS[cls]) {
    lines.push(CLASS_BLURBS[cls])
    lines.push('')
  }
  lines.push('| Variable | Required | Secret | Default | Subsystem | Purpose |')
  lines.push('| --- | --- | --- | --- | --- | --- |')
  for (const [name, v] of entries) {
    lines.push(
      `| \`${name}\` | ${esc(v.required)} | ${v.secret ? '**yes**' : 'no'} | ` +
        `${v.default === null ? '—' : `\`${v.default}\``} | ${esc(v.subsystem)} | ${esc(v.purpose)} |`,
    )
  }
  lines.push('')
  for (const [name, v] of entries) {
    if (!v.note) continue
    lines.push(`**\`${name}\`** — ${v.note}`)
    lines.push('')
  }
}

/* ----------------------------------------------------------- what cannot be scanned */

lines.push('## What a static scan cannot see')
lines.push('')
lines.push(
  'The conformance test reads the source and matches `process.env.X`, `process.env["X"]`, `env.X` and',
  '`env["X"]`. Four things are genuinely beyond it, and are stated here rather than implied:',
)
lines.push('')
lines.push(
  '1. **A computed name.** `worker.apiKeyEnv` makes the set of credential variables open-ended by',
  '   design, so the test pins the read SITES instead of the names. Those sites are:',
)
lines.push('')
for (const site of DYNAMIC_READ_SITES) {
  lines.push(`   - \`${site.file}\` — ${site.reason}`)
}
lines.push('')
lines.push(
  '2. **Anything a child process reads.** The report generator forwards its environment to the',
  '   analytics CLI it spawns, and the hook inherits whatever Claude Code gave it.',
  '3. **Anything Node itself reads**, such as `NODE_OPTIONS`, `TZ`, or the home-directory variables',
  '   consulted by `os.homedir()`.',
  '4. **Whether a declared purpose is true.** Only the name set and the read sites are machine',
  '   checkable; the meaning in these tables is prose, and prose is reviewed, not verified.',
)
lines.push('')

const exceptions = Object.entries(SPEC_ENV_EXCEPTIONS)
if (exceptions.length > 0) {
  lines.push('## Declared exceptions')
  lines.push('')
  lines.push(
    'A `CMR_*` name should appear in exactly one place — the config loader — so the layering stays',
    'testable and nothing reads a setting behind its back. These are the declared exceptions, listed',
    'so the list cannot grow silently:',
  )
  lines.push('')
  for (const [file, names] of exceptions) {
    lines.push(`- \`${file}\` reads ${names.map((n) => `\`${n}\``).join(', ')} directly.`)
  }
  lines.push('')
}

lines.push('## See also')
lines.push('')
lines.push('- [configuration.md](configuration.md) — what each setting does, and the precedence order')
lines.push('- [troubleshooting.md](troubleshooting.md) — when a variable appears to be ignored')
lines.push('')

const next = lines.join('\n')
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null
if (prev === next) {
  console.log(`docs/environment.md already up to date (${out})`)
} else {
  fs.writeFileSync(out, next)
  console.log(`${prev === null ? 'wrote' : 'updated'} ${out}`)
}
