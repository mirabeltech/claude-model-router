/**
 * THE WHOLE-REPOSITORY IMPORT GRAPH, as one machine-checkable artifact.
 *
 * WHAT THIS ADDS THAT THE EIGHT ISOLATION TESTS DO NOT. Layering in this repository is enforced by
 * seven per-directory allowlists plus a security gate, each with its own copy of an import regex.
 * That is strong where it looks and silent where it does not, and three areas were never looked at
 * at all: `lib/providers/`, `lib/doctor/`, and the top-level `lib/*.mjs` files. Nothing built a
 * whole-repository edge list, and nothing detected a cycle.
 *
 * It also replaces luck with reading. Measured against the 199 distinct edges in `plugins/**`, the
 * single-line regex in `telemetry.isolation.test.mjs` and `hook.security.test.mjs` cannot see 23 of
 * them, because it cannot match a multi-line `import {\n ... \n} from`. Two of those 23 matter:
 *
 *   - the dispatch allowlist (`telemetry.isolation.test.mjs:181`) never sees
 *     `dispatch/index.mjs -> ./contract.mjs` or `-> ../context-budget.mjs`. Both ARE permitted, so
 *     that test passes today by luck rather than by having read the edge.
 *   - the routing-purity test (`telemetry.isolation.test.mjs:100`) cannot see a multi-line
 *     `import {\n ... \n} from 'node:fs'`. CLAUDE.md's second non-negotiable is presently held by a
 *     raw-source `/node:/` check in a DIFFERENT file.
 *
 * Every edge in this file is read with `test/helpers/imports.mjs`, which is a lexer rather than a
 * regex and is a measured strict superset of all four existing bodies.
 *
 * WHY TWO DECLARATIONS AND NOT A RANK ALONE. A rank permits every DOWNWARD edge, so a rank alone
 * would allow `dispatch -> routing.mjs` and `telemetry -> routing.mjs` — which are exactly the two
 * edges `telemetry.isolation.test.mjs:90` and `:217` exist to ban. So a legal direction is not
 * sufficient: RANK fixes the order of the pipeline, and ALLOWED_TARGETS fixes who may speak to whom.
 *
 * WHY PER FILE AND NOT PER DIRECTORY. Three directories are not homogeneous.
 * `providers/capability.mjs`, `governance/policy.mjs` and `doctor/report.mjs` import nothing and are
 * read by layers that must not touch their directories. Declaring them as rank-0 shared leaves is
 * what CLAUDE.md already says about them in prose, and it means `config.mjs -> capability.mjs`,
 * `dispatch/modes.mjs -> routing-policy.mjs` and `redact.mjs`'s seven importers are legal BY
 * CONSTRUCTION rather than by exemption. The justification lives on the leaf.
 */

