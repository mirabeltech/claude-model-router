/* ------------------------------------------------------------------ build the graph */

const walk = (dir, out = []) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === '.git' || e.name === '.tmp') continue
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p, out)
    else if (e.name.endsWith('.mjs')) out.push(p)
  }
  return out
}

const filesOnDisk = () =>
  walk(path.join(ROOT, 'plugins'))
    .map((p) => slash(path.relative(ROOT, p)))
    .sort()

/** [{from, to, spec}] for every relative specifier, plus the builtins and unresolvables. */
const buildGraph = () => {
  const edges = []
  const builtins = new Map()
  const computed = []
  for (const rel of filesOnDisk()) {
    const { specs, computed: c } = scanImports(read(rel))
    if (c.length > 0) computed.push({ file: rel, forms: c })
    for (const spec of specs) {
      if (!spec.startsWith('.')) {
        if (!builtins.has(rel)) builtins.set(rel, [])
        builtins.get(rel).push(spec)
        continue
      }
      const to = slash(path.relative(ROOT, path.resolve(path.dirname(path.join(ROOT, rel)), spec)))
      edges.push({ from: rel, to, spec })
    }
  }
  return { edges, builtins, computed }
}

const GRAPH = buildGraph()
const EDGES = GRAPH.edges
const BY_SOURCE = new Map()
for (const e of EDGES) {
  if (!BY_SOURCE.has(e.from)) BY_SOURCE.set(e.from, [])
  BY_SOURCE.get(e.from).push(e.to)
}
const outDegree = (f) => (BY_SOURCE.get(f) ?? []).length
const pluginOf = (f) => (f.startsWith(`${DASHBOARD}/`) ? 'router-dashboard' : 'model-router')

