test('the import graph is acyclic, and names the cycle when it is not', () => {
  // Nothing in this repository detected a cycle before this test. A cycle is not a style problem:
  // telemetry -> analytics -> telemetry would put a reporting concern inside the module a
  // PreToolUse hook writes through, and analytics.isolation.test.mjs:410 bans exactly that ONE pair
  // by name. This bans the general case, including a three-hop cycle nobody thought to name.
  //
  // It is the complement of the rank rule: the only cycle the rank rule can permit is one built
  // entirely from same-rank, same-module edges, which is precisely what this finds.
  const WHITE = 0
  const GREY = 1
  const BLACK = 2
  const colour = new Map(Object.keys(ALL).map((f) => [f, WHITE]))
  const cycles = []

  for (const root of [...colour.keys()].sort()) {
    if (colour.get(root) !== WHITE) continue
    colour.set(root, GREY)
    const stack = [{ node: root, next: 0 }]
    while (stack.length > 0) {
      const top = stack[stack.length - 1]
      const kids = BY_SOURCE.get(top.node) ?? []
      if (top.next >= kids.length) {
        colour.set(top.node, BLACK)
        stack.pop()
        continue
      }
      const child = kids[top.next]
      top.next += 1
      if (!colour.has(child)) continue
      if (colour.get(child) === GREY) {
        const at = stack.findIndex((f) => f.node === child)
        cycles.push([...stack.slice(at).map((f) => f.node), child].join(' -> '))
        continue
      }
      if (colour.get(child) === WHITE) {
        colour.set(child, GREY)
        stack.push({ node: child, next: 0 })
      }
    }
  }
  assert.deepEqual(cycles, [], 'an import cycle')
})

